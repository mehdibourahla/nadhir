/**
 * Deterministic slugifier for Algerian wilaya French names (Loi 26-06).
 * Strips NFD combining diacritics, drops apostrophes (M'Sila -> msila,
 * El M'Ghair -> el-mghair), lowercases, and collapses non-alnum runs to hyphens.
 */
export function slugifyWilayaName(nameFr: string): string {
  return nameFr
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/['\u2019`]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");
}

